// Generates src/content/us-map.ts: projected, simplified SVG paths for every state + key city points.
// Source: us-atlas (US Census Bureau cartographic boundaries). Run: node scripts/build-us-map.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { geoAlbersUsa, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const topo = JSON.parse(readFileSync(new URL("../node_modules/us-atlas/states-10m.json", import.meta.url)));
const projection = geoAlbersUsa().scale(1300).translate([487.5, 305]);
const centroidPath = geoPath(projection);

const TOLERANCE = 0.55; // px, Douglas-Peucker
const MIN_AREA = 8; // px², drop specks (small islands)

function simplify(points) {
  if (points.length < 4) return points;
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = points[a];
    const [bx, by] = points[b];
    const dx = bx - ax, dy = by - ay;
    const len = Math.hypot(dx, dy) || 1;
    let max = 0, idx = -1;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * points[i][0] - dx * points[i][1] + bx * ay - by * ax) / len;
      if (d > max) { max = d; idx = i; }
    }
    if (max > TOLERANCE && idx > 0) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return points.filter((_, i) => keep[i]);
}

const area = (pts) => Math.abs(pts.reduce((s, [x, y], i) => { const [x2, y2] = pts[(i + 1) % pts.length]; return s + x * y2 - x2 * y; }, 0)) / 2;
const fmt = (n) => (Math.round(n * 2) / 2).toString();

function ringToPath(ring) {
  const projected = ring.map((c) => projection(c)).filter(Boolean);
  if (projected.length < 3 || area(projected) < MIN_AREA) return "";
  // Rings are closed (first point == last), which degenerates Douglas-Peucker: split at the
  // point farthest from the start and simplify the two open halves.
  let far = 0, farD = -1;
  projected.forEach(([x, y], i) => { const d = Math.hypot(x - projected[0][0], y - projected[0][1]); if (d > farD) { farD = d; far = i; } });
  const pts = [...simplify(projected.slice(0, far + 1)), ...simplify(projected.slice(far)).slice(1)];
  if (pts.length < 3) return "";
  return "M" + pts.map(([x, y]) => `${fmt(x)},${fmt(y)}`).join("L") + "Z";
}

function featureToPath(f) {
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  return polys.map((poly) => poly.map(ringToPath).join("")).join("");
}

const codes = {
  Alabama: "AL", Alaska: "AK", Arizona: "AZ", Arkansas: "AR", California: "CA", Colorado: "CO", Connecticut: "CT",
  Delaware: "DE", "District of Columbia": "DC", Florida: "FL", Georgia: "GA", Hawaii: "HI", Idaho: "ID", Illinois: "IL",
  Indiana: "IN", Iowa: "IA", Kansas: "KS", Kentucky: "KY", Louisiana: "LA", Maine: "ME", Maryland: "MD",
  Massachusetts: "MA", Michigan: "MI", Minnesota: "MN", Mississippi: "MS", Missouri: "MO", Montana: "MT", Nebraska: "NE",
  Nevada: "NV", "New Hampshire": "NH", "New Jersey": "NJ", "New Mexico": "NM", "New York": "NY", "North Carolina": "NC",
  "North Dakota": "ND", Ohio: "OH", Oklahoma: "OK", Oregon: "OR", Pennsylvania: "PA", "Rhode Island": "RI",
  "South Carolina": "SC", "South Dakota": "SD", Tennessee: "TN", Texas: "TX", Utah: "UT", Vermont: "VT", Virginia: "VA",
  Washington: "WA", "West Virginia": "WV", Wisconsin: "WI", Wyoming: "WY",
};

const states = feature(topo, topo.objects.states)
  .features.map((f) => {
    const code = codes[f.properties.name];
    if (!code) return null;
    const d = featureToPath(f);
    if (!d) return null;
    const [cx, cy] = centroidPath.centroid(f);
    return { code, name: f.properties.name, d, cx: Math.round(cx), cy: Math.round(cy) };
  })
  .filter(Boolean)
  .sort((a, b) => a.code.localeCompare(b.code));

// [lon, lat] for the factory, HQ and the anchor metro used for each Western state.
const cities = {
  factory: [-111.89, 40.76], // Salt Lake City, UT
  hq: [-78.48, 35.79], // Knightdale, NC
  UT: [-111.66, 40.23], // Provo
  ID: [-116.2, 43.62], // Boise
  NV: [-115.14, 36.17], // Las Vegas
  AZ: [-112.07, 33.45], // Phoenix
  CO: [-104.99, 39.74], // Denver
  WY: [-104.82, 41.14], // Cheyenne
  MT: [-108.5, 45.78], // Billings
  NM: [-106.65, 35.08], // Albuquerque
  CA: [-118.24, 34.05], // Los Angeles
  OR: [-122.68, 45.52], // Portland
  WA: [-122.33, 47.61], // Seattle
};
const points = Object.fromEntries(
  Object.entries(cities).map(([k, ll]) => {
    const p = projection(ll);
    return [k, [Math.round(p[0] * 10) / 10, Math.round(p[1] * 10) / 10]];
  }),
);

const out = `// GENERATED by scripts/build-us-map.mjs from us-atlas (US Census Bureau boundaries). Do not edit.
export const US_VIEWBOX = "0 0 975 610";

export type StateShape = { code: string; name: string; d: string; cx: number; cy: number };

export const stateShapes: StateShape[] = ${JSON.stringify(states)};

/** Projected [x, y] points (same projection as the shapes). */
export const mapPoints: Record<string, [number, number]> = ${JSON.stringify(points)};
`;
writeFileSync(new URL("../src/content/us-map.ts", import.meta.url), out);
console.log(`states: ${states.length}, bytes: ${out.length}`);
